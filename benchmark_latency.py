    "import sys\n",
    "import time\n",
    "from pathlib import Path\n",
    "from statistics import mean, median\n",
    "\n",
    "# src 모듈 경로 등록\n",
    "sys.path.append(\"src\")\n",
    "\n",
    "from ossp_router.heuristic import complexity_score, extract_features\n",
    "from ossp_router.protocol import load_input\n",
    "\n",
    "\n",
    "def run_benchmark(input_path: Path, num_runs: int = 3):\n",
    "    \"\"\"1,760개 문항에 대해 Feature Extraction + Complexity Scoring 지연시간 측정\"\"\"\n",
    "    print(f\" 데이터 로딩 중: {input_path}\")\n",
    "    if not input_path.exists():\n",
    "        print(f\" 오류: 입력 파일을 찾을 수 없습니다: {input_path}\")\n",
    "        sys.exit(1)\n",
    "\n",
    "    inputs = load_input(input_path)\n",
    "    episodes = inputs.episodes\n",
    "    total_episodes = len(episodes)\n",
    "    print(f\" 데이터 로드 완료 (총 {total_episodes:,}개 문항)\")\n",
    "\n",
    "    # 1. Warm-up (파이썬 모듈 로딩 및 캐시 영향 제거)\n",
    "    print(\"\\n Warm-up 실행 중 (50개 문항)...\")\n",
    "    for ep in episodes[:50]:\n",
    "        _ = complexity_score(extract_features(ep))\n",
    "\n",
    "    # 2. 벤치마크 측정\n",
    "    print(f\"⚡ 벤치마크 측정 시작 (총 {num_runs}회 반복 측정)...\")\n",
    "    all_latencies_ms = []\n",
    "\n",
    "    for run in range(1, num_runs + 1):\n",
    "        print(f\"   └ Iteration {run}/{num_runs} 진행 중...\")\n",
    "        for ep in episodes:\n",
    "            start_time = time.perf_counter()\n",
    "\n",
    "            # ML1 핵심 측정 대상: 특징 추출 + 복잡도 점수 산출\n",
    "            features = extract_features(ep)\n",
    "            _ = complexity_score(features)\n",
    "\n",
    "            end_time = time.perf_counter()\n",
    "\n",
    "            # 초(s)단위를 밀리초(ms)로 변환\n",
    "            latency_ms = (end_time - start_time) * 1000.0\n",
    "            all_latencies_ms.append(latency_ms)\n",
    "\n",
    "    # 3. 통계 계산 (P50, P95, P99, Mean, Max)\n",
    "    sorted_latencies = sorted(all_latencies_ms)\n",
    "    total_samples = len(sorted_latencies)\n",
    "\n",
    "    avg_lat = mean(sorted_latencies)\n",
    "    p50_lat = median(sorted_latencies)\n",
    "    p95_lat = sorted_latencies[int(total_samples * 0.95)]\n",
    "    p99_lat = sorted_latencies[int(total_samples * 0.99)]\n",
    "    max_lat = sorted_latencies[-1]\n",
    "    min_lat = sorted_latencies[0]\n",
    "\n",
    "    total_elapsed_sec = sum(all_latencies_ms) / 1000.0\n",
    "\n",
    "    # 4. 결과 출력 리포트\n",
    "    print(\"\\n==================================================\")\n",
    "    print(\"  ML1 Inference Latency Benchmark Report\")\n",
    "    print(\"==================================================\")\n",
    "    print(f\"• 총 평가 샘플 수   : {total_samples:,}회 ({total_episodes}개 × {num_runs}회)\")\n",
    "    print(f\"• 총 소요 시간      : {total_elapsed_sec:.3f} 초\")\n",
    "    print(\"--------------------------------------------------\")\n",
    "    print(f\"• 평균 지연시간     : {avg_lat:.4f} ms\")\n",
    "    print(f\"• 최소 지연시간     : {min_lat:.4f} ms\")\n",
    "    print(f\"• P50 (중앙값)      : {p50_lat:.4f} ms\")\n",
    "    print(f\"• P95 (상위 5%)     : {p95_lat:.4f} ms\")\n",
    "    print(f\"• P99 (상위 1%)     : {p99_lat:.4f} ms\")\n",
    "    print(f\"• 최대 지연시간     : {max_lat:.4f} ms\")\n",
    "    print(\"==================================================\")\n",
    "\n",
    "    # 스펙 검증 (< 10ms)\n",
    "    target_limit_ms = 10.0\n",
    "    if p99_lat < target_limit_ms:\n",
    "        print(f\" PASS: P99 지연시간({p99_lat:.4f}ms)이 스펙 제약조건({target_limit_ms}ms)을 충족합니다.\")\n",
    "    else:\n",
    "        print(f\" FAIL: P99 지연시간({p99_lat:.4f}ms)이 목표 기준({target_limit_ms}ms)을 초과했습니다.\")\n",
    "    print(\"==================================================\\n\")\n",
    "\n",
    "\n",
    "if __name__ == \"__main__\":\n",
    "    data_path = Path(\"data/materialized/train/inputs.json\")\n",
    "    run_benchmark(data_path, num_runs=3)"
